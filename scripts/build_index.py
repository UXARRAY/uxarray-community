#!/usr/bin/env python
"""Validate community entries and generate INDEX.md from their metadata.

Usage:
    python scripts/build_index.py           # validate, then write INDEX.md
    python scripts/build_index.py --check   # validate only (used in CI on pull requests)
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ENTRIES = ROOT / "entries"
INDEX = ROOT / "INDEX.md"

NAME_RE = re.compile(r"^(\d{4})-(\d{2})-(\d{2})_[a-z0-9]+(?:-[a-z0-9]+)*$")
FRONT_MATTER_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*(?:\n|\Z)", re.DOTALL)
TYPES = {"demo", "question", "workshop", "other"}
STATUSES = {"active", "superseded"}
REQUIRED = ("title", "type", "authors", "uxarray_version")


def load_entry(path: Path) -> tuple[dict | None, list[str]]:
    """Return (entry, errors) for one entry folder."""
    rel = path.relative_to(ROOT)
    errors: list[str] = []

    match = NAME_RE.match(path.name)
    if not match:
        return None, [f"{rel}: folder name must be YYYY-MM-DD_slug (lowercase, digits, hyphens)"]
    year, month, day = (int(g) for g in match.groups())
    try:
        date = dt.date(year, month, day)
    except ValueError:
        return None, [f"{rel}: {path.name[:10]} is not a valid date"]
    if path.parent.name != str(year):
        errors.append(f"{rel}: should be under entries/{year}/")

    readme = path / "README.md"
    if not readme.is_file():
        return None, errors + [f"{rel}: missing README.md"]
    fm = FRONT_MATTER_RE.match(readme.read_text(encoding="utf-8"))
    if not fm:
        return None, errors + [f"{rel}/README.md: missing metadata block between '---' lines"]
    try:
        meta = yaml.safe_load(fm.group(1)) or {}
    except yaml.YAMLError as exc:
        return None, errors + [f"{rel}/README.md: invalid YAML in metadata: {exc}"]
    if not isinstance(meta, dict):
        return None, errors + [f"{rel}/README.md: metadata must be a mapping"]

    for key in REQUIRED:
        if not meta.get(key):
            errors.append(f"{rel}/README.md: missing required field '{key}'")
    if meta.get("type") and meta["type"] not in TYPES:
        errors.append(f"{rel}/README.md: type must be one of {sorted(TYPES)}")
    status = meta.get("status") or "active"
    if status not in STATUSES:
        errors.append(f"{rel}/README.md: status must be one of {sorted(STATUSES)}")
    authors = meta.get("authors")
    if isinstance(authors, str):
        authors = [authors]
    if authors is not None and not isinstance(authors, list):
        errors.append(f"{rel}/README.md: authors must be a list")
    tags = meta.get("tags") or []
    if not isinstance(tags, list):
        errors.append(f"{rel}/README.md: tags must be a list")
        tags = []
    if not (path / "environment.yml").is_file():
        errors.append(f"{rel}: missing environment.yml")

    entry = {
        "date": date,
        "path": rel.as_posix(),
        "title": str(meta.get("title", path.name)),
        "type": meta.get("type", ""),
        "authors": [str(a) for a in authors or []],
        "uxarray_version": str(meta.get("uxarray_version", "")),
        "status": status,
        "tags": [str(t) for t in tags],
    }
    return entry, errors


def collect() -> tuple[list[dict], list[str]]:
    entries, errors = [], []
    if not ENTRIES.is_dir():
        return entries, errors
    for year_dir in sorted(p for p in ENTRIES.iterdir() if p.is_dir()):
        if not re.fullmatch(r"\d{4}", year_dir.name):
            errors.append(f"{year_dir.relative_to(ROOT)}: top-level folders in entries/ must be years")
            continue
        for path in sorted(p for p in year_dir.iterdir() if p.is_dir()):
            entry, errs = load_entry(path)
            errors.extend(errs)
            if entry:
                entries.append(entry)
    return entries, errors


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(entries: list[dict]) -> str:
    lines = [
        "# Index",
        "",
        "<!-- Generated by scripts/build_index.py. Do not edit by hand. -->",
        "",
    ]
    if not entries:
        lines += ["No entries yet. See [CONTRIBUTING.md](CONTRIBUTING.md) to add the first one.", ""]
        return "\n".join(lines)

    counts = {t: sum(e["type"] == t for e in entries) for t in sorted(TYPES)}
    summary = ", ".join(f"{n} {t}" for t, n in counts.items() if n)
    lines += [f"{len(entries)} entries ({summary}). Newest first.", ""]

    entries = sorted(entries, key=lambda e: (e["date"], e["path"]), reverse=True)
    for year in sorted({e["date"].year for e in entries}, reverse=True):
        lines += [
            f"## {year}",
            "",
            "| Date | Title | Type | Authors | UXarray | Tags |",
            "|------|-------|------|---------|---------|------|",
        ]
        for e in (e for e in entries if e["date"].year == year):
            title = f"[{cell(e['title'])}]({e['path']}/)"
            if e["status"] == "superseded":
                title = f"~~{title}~~ (superseded)"
            authors = ", ".join(f"@{a.lstrip('@')}" for a in e["authors"])
            tags = " ".join(f"`{cell(t)}`" for t in e["tags"])
            lines.append(
                f"| {e['date'].isoformat()} | {title} | {e['type']} | {authors} "
                f"| {cell(e['uxarray_version'])} | {tags} |"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="validate only; don't write INDEX.md")
    args = parser.parse_args()

    entries, errors = collect()
    for err in errors:
        print(f"error: {err}", file=sys.stderr)
    if errors:
        print(f"\n{len(errors)} problem(s) found.", file=sys.stderr)
        return 1

    if args.check:
        print(f"OK: {len(entries)} valid entries.")
        return 0

    INDEX.write_text(render(entries), encoding="utf-8")
    print(f"Wrote {INDEX.relative_to(ROOT)} with {len(entries)} entries.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
